import os
import gc
import numpy as np
import pandas as pd
import tensorflow as tf
import matplotlib.pyplot as plt
from tensorflow.keras import layers, models, optimizers, callbacks
from tensorflow.keras.applications import (
    MobileNetV2, ResNet50, DenseNet121, mobilenet_v2, resnet50, densenet)
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from sklearn.metrics import (accuracy_score, classification_report,
                             precision_score, recall_score, roc_auc_score)
from sklearn.model_selection import train_test_split
from sklearn.utils import class_weight
from google.colab import drive

# ==========================================
# 0. Configuration
# ==========================================
SEED = 42
IMG_SIZE = (224, 224)
BATCH_SIZE = 32
EPOCHS = 12            # EarlyStopping decides when to actually stop
LEARNING_RATE = 1e-3   # standard for training a small head on a frozen backbone;
                       # ReduceLROnPlateau lowers it automatically when val_loss stalls

# Re-draw the validation set from train+val, stratified by (source, label).
# Why: the official Kaggle "val" folder has only 16 images, and the merged val set
# may have a very different class/source mix than train. The TEST set is untouched.
RESPLIT_VAL = True
VAL_FRACTION = 0.15

tf.keras.utils.set_random_seed(SEED)

# Each backbone is paired with ITS OWN preprocess_input (they normalise differently).
BACKBONES = {
    'MobileNetV2': (MobileNetV2, mobilenet_v2.preprocess_input),
    'ResNet50':    (ResNet50,    resnet50.preprocess_input),
    'DenseNet121': (DenseNet121, densenet.preprocess_input),
}

# ==========================================
# 1. Load and merge the two datasets
# ==========================================
drive.mount('/content/drive')

BASE_DIR = '/content/drive/MyDrive/Ml_projects/InnoTech_Dataset'
CSV_PATH = os.path.join(BASE_DIR, 'cnn_data.csv')
IMAGES_DIR = os.path.join(BASE_DIR, 'images_224')
KAGGLE_DIR = '/content/new_chest_data/chest_xray'
COLUMNS = ['full_path', 'label_num', 'split', 'source']

# --- Indiana (CSV) ---
df_indiana = pd.read_csv(CSV_PATH)
df_indiana['full_path'] = df_indiana['filename'].apply(lambda f: os.path.join(IMAGES_DIR, f))
df_indiana['label_num'] = df_indiana['label'].astype(int)
df_indiana['source'] = 'indiana'
df_indiana = df_indiana[COLUMNS]

# --- Kaggle (folder structure: split/class/image) ---
rows = []
for split in ['train', 'val', 'test']:
    for label, class_name in enumerate(['NORMAL', 'PNEUMONIA']):   # NORMAL=0, PNEUMONIA=1
        folder = os.path.join(KAGGLE_DIR, split, class_name)
        if not os.path.isdir(folder):
            continue
        for fname in os.listdir(folder):
            if fname.lower().endswith(('.jpeg', '.jpg', '.png')):
                rows.append((os.path.join(folder, fname), label, split, 'kaggle'))
df_kaggle = pd.DataFrame(rows, columns=COLUMNS)

df = pd.concat([df_indiana, df_kaggle], ignore_index=True)

# Drop rows whose file is missing, so dataframe rows always match generator output
# (this is what keeps y_true aligned with the predictions later).
exists = df['full_path'].map(os.path.exists)
if not exists.all():
    print(f'Dropping {(~exists).sum()} rows with missing image files')
df = df[exists].reset_index(drop=True)

# ==========================================
# 2. Splits, diagnostics, class weights
# ==========================================
if RESPLIT_VAL:
    pool = df[df['split'] != 'test']
    strata = pool['source'] + '_' + pool['label_num'].astype(str)
    _, val_idx = train_test_split(pool.index, test_size=VAL_FRACTION,
                                  stratify=strata, random_state=SEED)
    df.loc[pool.index, 'split'] = 'train'
    df.loc[val_idx, 'split'] = 'val'

# Sanity check: look at the class/source mix of each split before training.
print('\nImages per split / source / label (0=NORMAL, 1=PNEUMONIA):')
print(pd.crosstab([df['split'], df['source']], df['label_num'], margins=True))

train_df = df[df['split'] == 'train']
val_df = df[df['split'] == 'val']
test_df = df[df['split'] == 'test']

cw = class_weight.compute_class_weight('balanced', classes=np.array([0, 1]),
                                       y=train_df['label_num'])
class_weights_dict = dict(enumerate(cw))
print('\nClass weights:', class_weights_dict)

# ==========================================
# 3. Helpers: generators and model
# ==========================================
def make_generators(preprocess_fn):
    """Augmented train generator + plain val/test generators (no shuffling for eval)."""
    train_datagen = ImageDataGenerator(
        preprocessing_function=preprocess_fn,
        rotation_range=20,
        width_shift_range=0.1,
        height_shift_range=0.1,
        zoom_range=0.2,
        brightness_range=(0.8, 1.2),
        # No horizontal flip: it produces anatomically unrealistic X-rays (heart on the right).
    )
    eval_datagen = ImageDataGenerator(preprocessing_function=preprocess_fn)

    def flow(frame, datagen, shuffle):
        return datagen.flow_from_dataframe(
            frame, x_col='full_path', y_col='label_num',
            target_size=IMG_SIZE, batch_size=BATCH_SIZE,
            class_mode='raw', shuffle=shuffle, seed=SEED,
            validate_filenames=False)   # files were already checked above

    return flow(train_df, train_datagen, True), flow(val_df, eval_datagen, False), flow(test_df, eval_datagen, False)


def build_model(backbone_cls):
    """Frozen ImageNet backbone + small, heavily regularised classification head."""
    base_model = backbone_cls(input_shape=(*IMG_SIZE, 3), include_top=False, weights='imagenet')
    base_model.trainable = False

    model = models.Sequential([
        base_model,
        layers.GlobalAveragePooling2D(),
        layers.Dropout(0.3),
        layers.Dense(64, activation='relu'),
        layers.Dropout(0.5),
        layers.Dense(1, activation='sigmoid'),
    ])
    model.compile(optimizer=optimizers.Adam(learning_rate=LEARNING_RATE),
                  loss='binary_crossentropy', metrics=['accuracy'])
    return model

# ==========================================
# 4. Train and evaluate each model
# ==========================================
results = []

for name, (backbone_cls, preprocess_fn) in BACKBONES.items():
    print(f'\n{"=" * 50}\nTraining {name}\n{"=" * 50}')
    tf.keras.backend.clear_session()
    gc.collect()

    train_gen, val_gen, test_gen = make_generators(preprocess_fn)
    assert train_gen.n == len(train_df) and test_gen.n == len(test_df)

    model = build_model(backbone_cls)

    cbs = [
        # Cut the learning rate when val_loss stalls...
        callbacks.ReduceLROnPlateau(monitor='val_loss', factor=0.3, patience=2,
                                    min_lr=1e-6, verbose=1),
        # ...and stop (keeping the best weights) if it still doesn't improve.
        callbacks.EarlyStopping(monitor='val_loss', patience=4, restore_best_weights=True),
    ]
    model.fit(train_gen, validation_data=val_gen, epochs=EPOCHS,
              class_weight=class_weights_dict, callbacks=cbs, verbose=1)

    # --- Evaluation on the test set ---
    # shuffle=False => predictions are in the same order as test_df, so the true labels
    # can be taken straight from the dataframe (class_mode='raw' has no `.classes`).
    probs = model.predict(test_gen, verbose=0).ravel()
    y_true = test_df['label_num'].values.astype(int)
    y_pred = (probs > 0.5).astype(int)
    assert len(y_true) == len(y_pred), 'labels and predictions are misaligned'

    print(f'\n{name} - test classification report:')
    print(classification_report(y_true, y_pred, target_names=['NORMAL', 'PNEUMONIA'],
                                zero_division=0))

    results.append({
        'Model': name,
        'Accuracy': accuracy_score(y_true, y_pred),
        'Precision (Pneumonia)': precision_score(y_true, y_pred, zero_division=0),
        'Recall (Pneumonia)': recall_score(y_true, y_pred, zero_division=0),
        'AUC': roc_auc_score(y_true, probs),
    })

    model.save(os.path.join(BASE_DIR, f'{name}_merged_fixed.keras'))
    del model
    gc.collect()

# ==========================================
# 5. Comparison table and plot
# ==========================================
results_df = pd.DataFrame(results).round(4)
print('\nMODEL COMPARISON RESULTS (test set):')
print(results_df.to_string(index=False))

results_df.set_index('Model').plot(kind='bar', figsize=(10, 6), rot=0)
plt.title('Model Comparison on Merged Data (Test Set)')
plt.ylim(0, 1.0)
plt.legend(loc='lower right')
plt.tight_layout()
plt.show()